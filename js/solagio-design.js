/* solagio-design – Verhalten der gemeinsamen Bausteine.
 * Klassisches Skript (kein Modul), damit es auch unter file:// läuft.
 * Im <head> laden, nach js/symbole.js:
 *   <script src="js/symbole.js"></script>
 *   <script src="js/design.js"></script>
 * So steht der Modus fest, bevor die Seite gezeichnet wird (kein Aufblitzen).
 *
 * Bausteine, alle über Attribute im HTML:
 *   Modus      <button data-sd-theme="light|dark|system">
 *   Schrift    <button data-sd-size>  (schaltet große Schrift für Beamer und Tafel)
 *   Symbol     <span data-sd-icon="upload"></span>
 *   Dialog     <button data-sd-open="id-des-dialogs">, <button data-sd-close>
 *   Hochladen  <div class="sd-dropzone" data-sd-dropzone> mit <input type="file">
 *   Reiter     <div class="sd-tabs" role="tablist" data-sd-tabs>  (Strich und Pfeiltasten;
 *              das Umschalten von aria-selected macht die App)
 *
 * Für Inhalte, die eine App später einfügt: SolagioDesign.einrichten(element). */
(function () {
  "use strict";

  var THEME_KEY = "solagio_theme"; // derselbe Schlüssel wie in den Lern-Apps
  var wurzel = document.documentElement;

  /* ---------- Modus: hell, dunkel, System ---------- */

  function gemerkt() {
    try {
      var wert = window.localStorage.getItem(THEME_KEY);
      return wert === "light" || wert === "dark" ? wert : "system";
    } catch (fehler) {
      return "system"; // localStorage gesperrt (z. B. private Fenster)
    }
  }

  function setzeModus(modus, merken) {
    if (modus === "light" || modus === "dark") {
      wurzel.setAttribute("data-theme", modus);
    } else {
      modus = "system";
      wurzel.removeAttribute("data-theme");
    }
    if (merken) {
      try {
        if (modus === "system") window.localStorage.removeItem(THEME_KEY);
        else window.localStorage.setItem(THEME_KEY, modus);
      } catch (fehler) { /* Wahl gilt dann nur für diese Seite */ }
    }
    zeigeModus(modus);
  }

  function zeigeModus(modus) {
    var knoepfe = document.querySelectorAll("[data-sd-theme]");
    for (var i = 0; i < knoepfe.length; i++) {
      var aktiv = knoepfe[i].getAttribute("data-sd-theme") === modus;
      knoepfe[i].setAttribute("aria-pressed", aktiv ? "true" : "false");
    }
  }

  setzeModus(gemerkt(), false); // sofort, noch vor dem ersten Zeichnen

  /* ---------- Große Schrift (Beamer, Tafel) ---------- */

  var SIZE_KEY = "solagio_size";

  function schriftGross() { return wurzel.getAttribute("data-size") === "large"; }

  function setzeSchrift(gross, merken) {
    if (gross) wurzel.setAttribute("data-size", "large");
    else wurzel.removeAttribute("data-size");
    if (merken) {
      try {
        if (gross) window.localStorage.setItem(SIZE_KEY, "large");
        else window.localStorage.removeItem(SIZE_KEY);
      } catch (fehler) { /* Wahl gilt dann nur für diese Seite */ }
    }
    zeigeSchrift();
  }

  function zeigeSchrift() {
    var knoepfe = document.querySelectorAll("[data-sd-size]");
    for (var i = 0; i < knoepfe.length; i++) {
      knoepfe[i].setAttribute("aria-pressed", schriftGross() ? "true" : "false");
    }
  }

  try {
    setzeSchrift(window.localStorage.getItem(SIZE_KEY) === "large", false);
  } catch (fehler) { /* localStorage gesperrt: normale Schrift */ }

  /* ---------- Symbole ---------- */

  var SVG_NS = "http://www.w3.org/2000/svg";

  function symbol(name) {
    var pfade = (window.SOLAGIO_SYMBOLE || {})[name];
    if (!pfade) return null;
    var svg = document.createElementNS(SVG_NS, "svg");
    svg.setAttribute("viewBox", "0 0 24 24");
    svg.setAttribute("fill", "none");
    svg.setAttribute("stroke", "currentColor");
    svg.setAttribute("stroke-width", "2");
    svg.setAttribute("stroke-linecap", "round");
    svg.setAttribute("stroke-linejoin", "round");
    svg.setAttribute("aria-hidden", "true");
    svg.setAttribute("focusable", "false");
    for (var i = 0; i < pfade.length; i++) {
      var pfad = document.createElementNS(SVG_NS, "path");
      pfad.setAttribute("d", pfade[i]);
      svg.appendChild(pfad);
    }
    return svg;
  }

  function setzeSymbole(bereich) {
    var stellen = bereich.querySelectorAll("[data-sd-icon]");
    for (var i = 0; i < stellen.length; i++) {
      var stelle = stellen[i];
      var name = stelle.getAttribute("data-sd-icon");
      if (stelle.getAttribute("data-sd-icon-gesetzt") === name) continue;
      var svg = symbol(name);
      if (!svg) continue;
      stelle.textContent = "";
      stelle.appendChild(svg);
      stelle.classList.add("sd-icon");
      stelle.setAttribute("data-sd-icon-gesetzt", name);
    }
  }

  /* ---------- Dialoge ---------- */

  function oeffneDialog(dialog, ausloeser) {
    if (!dialog || typeof dialog.showModal !== "function" || dialog.open) return;
    dialog.sdAusloeser = ausloeser || null;
    dialog.showModal();
  }

  function richteDialogeEin(bereich) {
    var dialoge = bereich.querySelectorAll("dialog");
    for (var i = 0; i < dialoge.length; i++) {
      if (dialoge[i].sdEingerichtet) continue;
      dialoge[i].sdEingerichtet = true;
      // Klick neben das Fenster schließt (für Browser ohne closedby="any").
      dialoge[i].addEventListener("click", function (ereignis) {
        if (ereignis.target === this) this.close();
      });
      // Fokus zurück auf den Knopf, der den Dialog geöffnet hat.
      dialoge[i].addEventListener("close", function () {
        if (this.sdAusloeser && document.contains(this.sdAusloeser)) this.sdAusloeser.focus();
        this.sdAusloeser = null;
      });
    }
  }

  /* ---------- Hochladen ---------- */

  function groesse(bytes) {
    if (bytes < 1024) return bytes + " Byte";
    if (bytes < 1024 * 1024) return Math.round(bytes / 1024) + " KB";
    return (bytes / 1024 / 1024).toFixed(1).replace(".", ",") + " MB";
  }

  function zeigeDatei(zone) {
    var eingabe = zone.querySelector('input[type="file"]');
    var ziel = zone.querySelector("[data-sd-dropzone-file]");
    var dateien = eingabe ? eingabe.files : null;
    var gewaehlt = !!(dateien && dateien.length);
    zone.classList.toggle("sd-dropzone-filled", gewaehlt);
    if (!ziel) return;
    if (!gewaehlt) {
      ziel.textContent = "";
      return;
    }
    var namen = [];
    for (var i = 0; i < dateien.length; i++) {
      namen.push(dateien[i].name + " (" + groesse(dateien[i].size) + ")");
    }
    ziel.textContent = namen.join(", ");
  }

  function richteHochladenEin(bereich) {
    var zonen = bereich.querySelectorAll("[data-sd-dropzone]");
    for (var i = 0; i < zonen.length; i++) {
      (function (zone) {
        if (zone.sdEingerichtet) return;
        zone.sdEingerichtet = true;
        var eingabe = zone.querySelector('input[type="file"]');
        if (!eingabe) return;
        var tiefe = 0; // dragenter/dragleave feuern auch für Kindelemente

        eingabe.addEventListener("change", function () { zeigeDatei(zone); });
        zone.addEventListener("dragenter", function (ereignis) {
          ereignis.preventDefault();
          tiefe++;
          zone.classList.add("sd-dropzone-over");
        });
        zone.addEventListener("dragover", function (ereignis) { ereignis.preventDefault(); });
        zone.addEventListener("dragleave", function () {
          tiefe = Math.max(0, tiefe - 1);
          if (!tiefe) zone.classList.remove("sd-dropzone-over");
        });
        zone.addEventListener("drop", function (ereignis) {
          ereignis.preventDefault();
          tiefe = 0;
          zone.classList.remove("sd-dropzone-over");
          var dateien = ereignis.dataTransfer ? ereignis.dataTransfer.files : null;
          if (!dateien || !dateien.length || eingabe.disabled) return;
          try {
            eingabe.files = dateien;
          } catch (fehler) {
            return; // sehr alte Browser: Datei bitte über den Knopf wählen
          }
          eingabe.dispatchEvent(new Event("change", { bubbles: true }));
        });
        zeigeDatei(zone);
      })(zonen[i]);
    }
  }

  /* ---------- Reiter ---------- */

  var REITER_AKTIV = '[aria-selected="true"], [aria-current="page"], [aria-current="true"]';

  function reiterVon(leiste) {
    var alle = [];
    for (var i = 0; i < leiste.children.length; i++) {
      if (!leiste.children[i].classList.contains("sd-tabs-ink")) alle.push(leiste.children[i]);
    }
    return alle;
  }

  /* Setzt den Strich unter den aktiven Reiter und holt ihn ins Bild. */
  function zeigeReiter(leiste) {
    var reiter = reiterVon(leiste);
    var aktiv = null;
    for (var i = 0; i < reiter.length; i++) {
      if (!aktiv && reiter[i].matches(REITER_AKTIV)) aktiv = reiter[i];
    }
    if (leiste.getAttribute("role") === "tablist") {
      // Tab springt nur auf den aktiven Reiter, die Pfeiltasten wandern weiter.
      var ziel = aktiv && !aktiv.disabled ? aktiv : null;
      for (var j = 0; j < reiter.length; j++) {
        if (!ziel && !reiter[j].disabled) ziel = reiter[j];
      }
      for (var k = 0; k < reiter.length; k++) reiter[k].tabIndex = reiter[k] === ziel ? 0 : -1;
    }
    var strich = leiste.querySelector(":scope > .sd-tabs-ink");
    if (!strich) {
      strich = document.createElement("span");
      strich.className = "sd-tabs-ink";
      strich.setAttribute("aria-hidden", "true");
      leiste.appendChild(strich);
    }
    if (!aktiv) {
      strich.hidden = true;
      strich.removeAttribute("data-sd-bereit");
      return;
    }
    strich.hidden = false;
    var neu = !strich.hasAttribute("data-sd-bereit");
    if (neu) strich.style.transition = "none"; // beim ersten Mal ohne Fahrt vom Rand
    strich.style.width = aktiv.offsetWidth + "px";
    strich.style.transform = "translateX(" + aktiv.offsetLeft + "px)";
    if (neu) {
      void strich.offsetWidth;
      strich.style.transition = "";
      strich.setAttribute("data-sd-bereit", "");
    }
    var links = aktiv.offsetLeft;
    var rechts = links + aktiv.offsetWidth;
    if (links < leiste.scrollLeft) leiste.scrollLeft = Math.max(0, links - 16);
    else if (rechts > leiste.scrollLeft + leiste.clientWidth) leiste.scrollLeft = rechts - leiste.clientWidth + 16;
  }

  function reiterTaste(ereignis) {
    var leiste = ereignis.currentTarget;
    if (leiste.getAttribute("role") !== "tablist") return;
    var frei = reiterVon(leiste).filter(function (r) { return !r.disabled; });
    var stelle = frei.indexOf(document.activeElement);
    if (stelle < 0 || !frei.length) return;
    var neu = stelle;
    if (ereignis.key === "ArrowRight") neu = (stelle + 1) % frei.length;
    else if (ereignis.key === "ArrowLeft") neu = (stelle - 1 + frei.length) % frei.length;
    else if (ereignis.key === "Home") neu = 0;
    else if (ereignis.key === "End") neu = frei.length - 1;
    else return;
    ereignis.preventDefault();
    frei[neu].focus();
  }

  function richteReiterEin(bereich) {
    var leisten = bereich.querySelectorAll("[data-sd-tabs]");
    for (var i = 0; i < leisten.length; i++) {
      (function (leiste) {
        if (!leiste.hasAttribute("data-sd-tabs-gesetzt")) {
          leiste.setAttribute("data-sd-tabs-gesetzt", "");
          leiste.addEventListener("keydown", reiterTaste);
          // Die App schaltet aria-selected oder tauscht Reiter aus: der Strich zieht nach.
          new MutationObserver(function () { zeigeReiter(leiste); }).observe(leiste, {
            subtree: true, childList: true, attributes: true,
            attributeFilter: ["aria-selected", "aria-current", "disabled"]
          });
          // Breite oder Schriftgröße ändert sich.
          if (window.ResizeObserver) new ResizeObserver(function () { zeigeReiter(leiste); }).observe(leiste);
        }
        zeigeReiter(leiste);
      })(leisten[i]);
    }
  }

  /* ---------- Klicks (einmal für die ganze Seite) ---------- */

  document.addEventListener("click", function (ereignis) {
    var ziel = ereignis.target;
    if (!ziel || !ziel.closest) return;

    var modusKnopf = ziel.closest("[data-sd-theme]");
    if (modusKnopf) {
      setzeModus(modusKnopf.getAttribute("data-sd-theme"), true);
      return;
    }
    if (ziel.closest("[data-sd-size]")) {
      setzeSchrift(!schriftGross(), true);
      return;
    }
    var oeffner = ziel.closest("[data-sd-open]");
    if (oeffner) {
      oeffneDialog(document.getElementById(oeffner.getAttribute("data-sd-open")), oeffner);
      return;
    }
    var schliesser = ziel.closest("[data-sd-close]");
    if (schliesser) {
      var dialog = schliesser.closest("dialog");
      if (dialog) dialog.close();
    }
  });

  /* ---------- Einrichten ---------- */

  function einrichten(bereich) {
    bereich = bereich || document;
    setzeSymbole(bereich);
    richteDialogeEin(bereich);
    richteHochladenEin(bereich);
    richteReiterEin(bereich);
    zeigeModus(wurzel.getAttribute("data-theme") || "system");
    zeigeSchrift();
  }

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", function () { einrichten(document); });
  } else {
    einrichten(document);
  }

  window.SolagioDesign = {
    einrichten: einrichten,
    symbol: symbol,
    zeigeReiter: zeigeReiter,
    setzeModus: function (modus) { setzeModus(modus, true); },
    modus: function () { return wurzel.getAttribute("data-theme") || "system"; },
    setzeSchrift: function (gross) { setzeSchrift(!!gross, true); },
    schriftGross: schriftGross
  };
})();
